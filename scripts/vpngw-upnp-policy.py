"""Render a least-privilege miniupnpd IGD configuration for DIRECT hosts only.

This module does not start miniupnpd, install firewall rules, or claim that
VPN-provider port forwarding can be obtained through LAN UPnP.
The active policy agent must first verify host routing and the effective
firewall/backend of the installed miniupnpd binary.
"""
from __future__ import annotations

import ipaddress
import re
import uuid as uuidlib
from typing import Mapping

INTERFACE = re.compile(r"^[A-Za-z0-9_.-]{1,15}$")
DEFAULT_DENY = "deny 0-65535 0.0.0.0/0 0-65535"


class UPnPConfigError(ValueError):
    pass


def _interface(value: str) -> str:
    if not isinstance(value, str) or not INTERFACE.fullmatch(value):
        raise UPnPConfigError("Invalid interface")
    return value


def _host(value: str) -> str:
    try:
        address = ipaddress.ip_address(value)
    except ValueError as exc:
        raise UPnPConfigError("Invalid host IP") from exc
    if (address.version != 4 or not address.is_private
            or address.is_unspecified or address.is_loopback or address.is_multicast):
        raise UPnPConfigError("Only private LAN hosts are eligible")
    return str(address)


def eligibility(policies: Mapping[str, dict]) -> dict:
    """Separate actual IGD eligibility from VPN-provider NAT-PMP capability."""
    eligible = {}
    unsupported = {}
    for identifier, policy in policies.items():
        if not policy.get("upnp_enabled", True):
            continue
        route = policy.get("destination", "blocked")
        if route == "blocked":
            unsupported[identifier] = "blocked_route"
        elif route != "direct":
            unsupported[identifier] = "vpn_provider_mapping_required"
        elif policy.get("status") != "active":
            unsupported[identifier] = "host_policy_not_active"
        elif not policy.get("registered_mac"):
            unsupported[identifier] = "host_identity_not_confirmed"
        else:
            eligible[identifier] = _host(policy["host_ip"])
    return {"eligible_direct": eligible, "unsupported": unsupported}


def render_config(*, lan_interface: str, wan_interface: str,
                  allowed_hosts: list[str], uuid: str,
                  min_port: int = 1024, max_port: int = 65535) -> str:
    """Create strict ACLs. An empty host set permits no mappings."""
    lan = _interface(lan_interface)
    wan = _interface(wan_interface)
    if lan == wan:
        raise UPnPConfigError("Shared-interface IGD requires separate architecture review")
    try:
        parsed_uuid = uuidlib.UUID(uuid)
    except (TypeError, ValueError, AttributeError) as exc:
        raise UPnPConfigError("Invalid device UUID") from exc
    if str(parsed_uuid) != uuid.lower():
        raise UPnPConfigError("Non-canonical device UUID")
    if type(min_port) is not int or type(max_port) is not int or not (1024 <= min_port <= max_port <= 65535):
        raise UPnPConfigError("Invalid port range")
    hosts = sorted({_host(host) for host in allowed_hosts})
    result = [
        "# Generated by VPN Gateway; no automatic daemon activation.",
        f"ext_ifname={wan}",
        f"listening_ip={lan}",
        f"uuid={uuid}",
        "secure_mode=yes",
        "enable_upnp=yes",
        "enable_pcp_pmp=no",
        "ipv6_disable=yes",
        "ext_allow_private_ipv4=no",
        "system_uptime=yes",
        "# Only selected DIRECT host addresses may request mappings.",
    ]
    result.extend(
        f"allow {min_port}-{max_port} {host}/32 {min_port}-{max_port}"
        for host in hosts
    )
    result.append(DEFAULT_DENY)
    return "\n".join(result) + "\n"
